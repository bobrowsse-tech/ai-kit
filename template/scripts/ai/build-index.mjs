#!/usr/bin/env node
// Builds/refreshes the generated section of docs/functionality-index.md.
//   node scripts/ai/build-index.mjs           write the index
//   node scripts/ai/build-index.mjs --check   exit 1 if the index is stale (CI / pre-commit)
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, loadConfig, listSourceFiles, extractSymbols, formatSymbol, readText } from './lib.mjs';

const CHECK = process.argv.includes('--check');
const cfg = loadConfig();
const START = '<!-- AI-INDEX:START (generated by scripts/ai/build-index.mjs - edit outside the markers only) -->';
const END = '<!-- AI-INDEX:END -->';

const files = listSourceFiles(cfg);
const sections = [];
const byName = new Map();
let total = 0;
let undocumented = 0;

for (const rel of files) {
  const syms = extractSymbols(rel, readText(rel));
  if (!syms.length) continue;
  total += syms.length;
  sections.push(`### ${rel}\n${syms.map(formatSymbol).join('\n')}`);
  for (const s of syms) {
    if (!s.desc) undocumented++;
    if (cfg.ignoreNames.includes(s.name)) continue;
    if (!byName.has(s.name)) byName.set(s.name, new Set());
    byName.get(s.name).add(rel);
  }
}

const dupNames = [...byName].filter(([, f]) => f.size > 1).sort(([a], [b]) => a.localeCompare(b));
const lines = [];
if (total === 0) {
  lines.push(`_No exported symbols found under the configured roots (${cfg.roots.join(', ')}). Adjust .ai/config.json if code lives elsewhere._`);
} else {
  lines.push(`${total} symbols in ${sections.length} files. Search with: \`node scripts/ai/find.mjs <keywords>\` (do not read this whole file).`, '');
  lines.push(sections.join('\n\n'));
}
if (dupNames.length) {
  lines.push('', '## Same-name exports (possible duplicates - verify before adding more)');
  for (const [n, f] of dupNames) lines.push(`- \`${n}\`: ${[...f].join(', ')}`);
}

const block = `${START}\n${lines.join('\n')}\n${END}`;
const indexPath = path.join(ROOT, cfg.indexFile);
const existing = fs.existsSync(indexPath) ? fs.readFileSync(indexPath, 'utf8') : null;

let next;
if (existing === null) {
  next = `# Functionality Index\n\n> Registry of what already exists. Search before you create: node scripts/ai/find.mjs <keywords>\n\n${block}\n`;
} else if (existing.includes('<!-- AI-INDEX:START') && existing.includes(END)) {
  const s = existing.indexOf('<!-- AI-INDEX:START');
  const e = existing.indexOf(END) + END.length;
  next = existing.slice(0, s) + block + existing.slice(e);
} else {
  next = existing.replace(/\s*$/, '\n\n') + block + '\n';
}

if (CHECK) {
  const lf = (t) => (t === null ? t : t.replace(/\r\n/g, '\n'));
  if (lf(next) !== lf(existing)) {
    console.error(`\x1b[0;31m[ERROR] ${cfg.indexFile} is stale. Run: node scripts/ai/build-index.mjs (then commit it).\x1b[0m`);
    process.exit(1);
  }
  console.log(`\x1b[0;32m[OK] ${cfg.indexFile} is up to date (${total} symbols).\x1b[0m`);
} else {
  fs.mkdirSync(path.dirname(indexPath), { recursive: true });
  if (next !== existing) fs.writeFileSync(indexPath, next);
  console.log(`Indexed ${total} symbols in ${sections.length} files -> ${cfg.indexFile}`);
  if (undocumented) console.log(`[HINT] ${undocumented} symbols have no one-line doc comment; add one so reuse search can find them.`);
  if (dupNames.length) console.log(`[WARN] ${dupNames.length} exported name(s) appear in multiple files - possible duplicates (see index).`);
}
